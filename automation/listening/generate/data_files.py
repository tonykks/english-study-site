def _level_wordcard_sample(level: int, max_lines: int = 45) -> str:
    level_dir = LISTENING_ROOT / level_folder(level)
    if level_dir.is_dir():
        for folder in sorted(level_dir.iterdir()):
            wc = folder / "05_wordcard.txt"
            if wc.is_file():
                return "\n".join(wc.read_text(encoding="utf-8").splitlines()[:max_lines])
    return _few_shot("05_wordcard.txt", max_lines)


_NON_GERUND_ING = frozenset(
    {
        "building",
        "ceiling",
        "during",
        "evening",
        "feeling",
        "morning",
        "nothing",
        "something",
        "spring",
        "string",
        "thing",
    }
)


def _lemma_level1_headword(headword: str, part_of_speech: str) -> str:
    """Normalize -ing gerunds/participles to base verb lemma for Level 1 headwords."""
    word = headword.strip()
    lw = word.lower()
    if lw in _NON_GERUND_ING or len(lw) <= 4 or not lw.endswith("ing"):
        return word
    stem = lw[:-3]
    if len(stem) < 2:
        return word
    pos = part_of_speech.lower()
    if len(stem) >= 2 and stem[-1] == stem[-2] and stem[-1] not in "aeiou":
        lemma = stem[:-1]
    elif stem[-1] in "tvklgp" and not stem.endswith("e"):
        lemma = stem + "e"
    else:
        lemma = stem
    if pos.startswith("verb") or "participle" in pos or "gerund" in pos or pos == "noun":
        return lemma if word.islower() else lemma.capitalize()
    return word


def generate_wordcards_from_transcript(
    segments: list[Segment],
    core_text: str,
    level: int,
    *,
    allow_placeholder: bool = False,
) -> str:
    transcript = _transcript_text(segments)
    level_hint = _level_guidance(level)
    lemma_rule = ""
    if level == 1:
        lemma_rule = (
            "- Level 1 headword must use dictionary base/lemma form, NOT -ing gerund/participle forms "
            "(e.g. farming→farm, writing→write). Show the actual -ing form in example_en when needed.\n"
        )
    if vertex_configured() and not allow_placeholder:
        example = _level_wordcard_sample(level)
        data = generate_json(
            f"""Create vocabulary word cards for Level {level} English listening learners.
{level_hint}
Rules:
- Pick a natural count (typically around 10; range {WORDCARD_MIN}-{WORDCARD_MAX}) based on learning value, NOT a fixed number
- Priority: context importance > level fit > learning value
- Include words critical to understanding the video; do NOT pad with easy/common words
- Do NOT drop important words to hit a count
- Skip overly common function words, trivial words, words chosen only for length or early appearance
- Proper nouns only when essential for comprehension
- Return English fields only (Korean will be added separately)
- meaning_kr will be generated to MATCH part_of_speech (verb gloss must be a Korean verb)
{lemma_rule}
Return JSON: {{"cards": [{{"headword": "...", "part_of_speech": "...", "definition_en": "...", "example_en": "..."}}]}}

Reference Level {level} vocabulary style:
{example}

Transcript excerpt:
{transcript[:10000]}

Core sentences excerpt:
{core_text[:3000]}
"""
        )
        cards = data.get("cards", []) if isinstance(data, dict) else data
        if not isinstance(cards, list):
            raise RuntimeError("BLOCKED: Word card generation returned invalid format")
        if len(cards) < WORDCARD_MIN or len(cards) > WORDCARD_MAX:
            raise RuntimeError(
                f"BLOCKED: Word card generation returned {len(cards)} cards "
                f"(expected {WORDCARD_MIN}-{WORDCARD_MAX} based on content value)"
            )
        if level == 1:
            for card in cards:
                hw = str(card.get("headword", "")).strip()
                pos = str(card.get("part_of_speech", "")).strip()
                if hw:
                    card["headword"] = _lemma_level1_headword(hw, pos)
    else:
        cards = _heuristic_wordcards(core_text)

    return _format_wordcards(cards, allow_placeholder=allow_placeholder)


def _format_wordcards(cards: list[dict[str, Any]], *, allow_placeholder: bool) -> str:
    from automation.listening.vertex_client import meaning_matches_pos, translate_wordcard_meanings

    batch_items: list[tuple[str, str]] = []
    meaning_items: list[dict[str, str]] = []
    structured: list[dict[str, str]] = []
    for i, card in enumerate(cards, start=1):
        hw = str(card.get("headword", "word")).strip()
        pos = str(card.get("part_of_speech", "noun")).strip()
        def_en = str(card.get("definition_en", f"definition of {hw}")).strip()
        ex_en = str(card.get("example_en", f"This story mentions {hw}.")).strip()
        structured.append({"hw": hw, "pos": pos, "def_en": def_en, "ex_en": ex_en})
        meaning_items.append(
            {
                "id": f"c{i}_m",
                "headword": hw,
                "part_of_speech": pos,
                "definition_en": def_en,
                "example_en": ex_en,
            }
        )
        batch_items.append((f"c{i}_d", def_en))
        batch_items.append((f"c{i}_e", ex_en))

    kr_map = _translate_batch(batch_items, allow_placeholder=allow_placeholder)
    if allow_placeholder or not vertex_configured():
        meaning_map = {
            str(item["id"]): f"[KR pending: {item['headword']}]" for item in meaning_items
        }
        if not allow_placeholder and meaning_items:
            raise RuntimeError("BLOCKED: Vertex AI required for wordcard meanings")
    else:
        meaning_map = translate_wordcard_meanings(meaning_items)

    lines: list[str] = []
    for i, card in enumerate(structured, start=1):
        meaning_kr = meaning_map[f"c{i}_m"]
        if not allow_placeholder and not meaning_matches_pos(meaning_kr, card["pos"]):
            raise RuntimeError(
                f"BLOCKED: wordcard POS mismatch for {card['hw']} ({card['pos']}): {meaning_kr}"
            )
        conflict = meaning_conflicts_with_context(
            card["hw"], meaning_kr, card["def_en"], card["ex_en"]
        )
        if not allow_placeholder and conflict:
            raise RuntimeError(f"BLOCKED: wordcard sense mismatch for {card['hw']}: {conflict}")
        lines.append(f"[Card {i}]")
        lines.append(f"headword: {card['hw']}")
        lines.append(f"part_of_speech: {card['pos']}")
        lines.append(f"meaning_kr: {meaning_kr}")
        lines.append(f"definition_en: {card['def_en']}")
        lines.append(f"definition_kr_literal: {kr_map[f'c{i}_d']}")
        lines.append(f"example_en: {card['ex_en']}")
        lines.append(f"example_kr_literal: {kr_map[f'c{i}_e']}")
        lines.append("")
    return "\n".join(lines).strip() + "\n"


def translate_paragraphs_kr(paragraphs: list[str], *, allow_placeholder: bool = False) -> list[str]:
    """Translate each English sentence, then rejoin so KR units match EN sentence order."""
    if not paragraphs:
        return []
    if allow_placeholder:
        return [f"[KR translation pending: {p[:60]}...]" for p in paragraphs]

    items: list[tuple[str, str]] = []
    structure: list[list[str]] = []
    for i, para in enumerate(paragraphs, start=1):
        sents = [s.strip() for s in split_sentences(para) if s.strip()]
        if not sents:
            sents = [para.strip()] if para.strip() else [""]
        ids: list[str] = []
        for j, sent in enumerate(sents, start=1):
            sid = f"p{i}s{j}"
            items.append((sid, sent))
            ids.append(sid)
        structure.append(ids)

    kr_map = _translate_batch(items, allow_placeholder=allow_placeholder)
    assembled: list[str] = []
    for ids in structure:
        units: list[str] = []
        for sid in ids:
            unit = (kr_map.get(sid) or "").strip()
            unit = re.sub(r"[.!?]+", "", unit).strip()
            unit = re.sub(r"\s+", " ", unit)
            if unit:
                units.append(unit + ".")
        assembled.append(" ".join(units) if units else "")
    return assembled


