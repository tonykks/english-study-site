def build_04_en_manifest(segments: list[Segment]) -> list[dict[str, str]]:
    return [{"segment_id": s.segment_id, "hash": segment_hash(s.text_en)} for s in segments]


def assemble_04_en(segments: list[Segment]) -> tuple[str, list[dict[str, str]]]:
    paragraphs = group_paragraphs(segments)
    manifest = build_04_en_manifest(segments)
    lines: list[str] = []
    for i, para in enumerate(paragraphs, start=1):
        lines.append(f"[Paragraph {i}]")
        lines.append(f"EN: {para}")
        lines.append("KR: ")
    return "\n".join(lines).rstrip() + "\n", manifest


def verify_04_en_manifest(segments: list[Segment], content_04: str, manifest: list[dict[str, str]] | None = None) -> bool:
    manifest = manifest or build_04_en_manifest(segments)
    if len(manifest) != len(segments):
        return False
    en_blob = "\n".join(
        line[3:].strip()
        for line in content_04.splitlines()
        if line.strip().upper().startswith("EN:")
    )
    normalized_blob = re.sub(r"\s+", " ", en_blob).strip().lower()
    for entry, seg in zip(manifest, segments):
        expected = entry.get("hash") or segment_hash(seg.text_en)
        actual = segment_hash(seg.text_en)
        if expected != actual:
            return False
        needle = re.sub(r"\s+", " ", seg.text_en).strip().lower()
        if needle and needle not in normalized_blob:
            return False
    return len(manifest) > 0


def inject_kr_into_04(en_content: str, kr_paragraphs: list[str]) -> str:
    lines = en_content.splitlines()
    out: list[str] = []
    kr_idx = 0
    for line in lines:
        if line.strip().upper().startswith("KR:") and kr_idx < len(kr_paragraphs):
            out.append(f"KR: {kr_paragraphs[kr_idx]}")
            kr_idx += 1
        else:
            out.append(line)
    return "\n".join(out) + "\n"


