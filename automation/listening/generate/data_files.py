def _heuristic_wordcards(core_text: str) -> list[dict[str, Any]]:
    words = re.findall(r"\b[A-Za-z]{5,}\b", core_text)
    unique: list[str] = []
    skip = {"about", "there", "their", "which", "would", "could", "should", "every", "after"}
    for w in words:
        lw = w.lower()
        if lw in skip:
            continue
        if lw not in unique:
            unique.append(lw)
        if len(unique) >= 8:
            break
    if not unique:
        unique = ["lesson", "story"]
    return [
        {
            "headword": w,
            "part_of_speech": "noun",
            "definition_en": f"common English definition of {w}",
            "example_en": f"This story mentions {w} in an important moment.",
        }
        for w in unique
    ]


def _openai_literal(en: str, instruction: str | None = None) -> str:
    if not allow_openai_fallback():
        raise RuntimeError("BLOCKED: OpenAI fallback not allowed (set ALLOW_OPENAI_FALLBACK=1)")
    from openai import OpenAI

    prompt = instruction or LITERAL_KR_INSTRUCTION
    client = OpenAI()
    resp = client.chat.completions.create(
        model=os.getenv("OPENAI_MODEL", "gpt-4o-mini"),
        messages=[{"role": "user", "content": f"{prompt}\n\nEnglish:\n{en}"}],
    )
    return (resp.choices[0].message.content or "").strip()


def _count_blocks(content: str, label: str) -> int:
    return len(re.findall(rf"\[{re.escape(label)}\s+\d+\]", content))


def _verified_script_text(segments: list[Segment] | None, content_04: str) -> str:
    if segments:
        return " ".join(s.text_en for s in segments)
    en_lines = [
        line.split(":", 1)[1].strip()
        for line in content_04.splitlines()
        if line.strip().upper().startswith("EN:")
    ]
    return " ".join(en_lines)


def _validate_wordcards(content: str) -> tuple[bool, str]:
    blocks = re.split(r"\[Card\s+\d+\]", content)
    card_blocks = [b for b in blocks if b.strip()]
    if len(card_blocks) < WORDCARD_MIN:
        return False, f"05_wordcard.txt has {len(card_blocks)} cards, need at least {WORDCARD_MIN}"
    if len(card_blocks) > WORDCARD_MAX:
        return False, f"05_wordcard.txt has {len(card_blocks)} cards, exceeds {WORDCARD_MAX}"
    for i, block in enumerate(card_blocks, start=1):
        for field in WORDCARD_FIELDS:
            if field not in block:
                return False, f"05_wordcard.txt Card {i} missing {field.rstrip(':')}"
        pos_m = re.search(r"part_of_speech:\s*(.+)", block)
        kr_m = re.search(r"meaning_kr:\s*(.+)", block)
        if pos_m and kr_m:
            from automation.listening.vertex_client import meaning_matches_pos

            pos = pos_m.group(1).strip()
            kr = kr_m.group(1).strip()
            if kr and not kr.startswith("[KR") and not meaning_matches_pos(kr, pos):
                return False, f"05_wordcard.txt Card {i} POS mismatch ({pos}): {kr}"
        hw_m = re.search(r"headword:\s*(.+)", block)
        def_m = re.search(r"definition_en:\s*(.+)", block)
        ex_m = re.search(r"example_en:\s*(.+)", block)
        if hw_m and kr_m and def_m and ex_m:
            kr = kr_m.group(1).strip()
            if kr and not kr.startswith("[KR"):
                conflict = meaning_conflicts_with_context(
                    hw_m.group(1).strip(),
                    kr,
                    def_m.group(1).strip(),
                    ex_m.group(1).strip(),
                )
                if conflict:
                    return False, f"05_wordcard.txt Card {i} sense mismatch: {conflict}"
    return True, "OK"


def count_en_punctuation(content_04: str) -> dict[str, int]:
    en = " ".join(
        line.split(":", 1)[1]
        for line in content_04.splitlines()
        if line.strip().upper().startswith("EN:")
    )
    return {ch: en.count(ch) for ch in ". ,?!:;".replace(" ", "")}


def _04_paragraph_pairs(content_04: str) -> list[tuple[str, str]]:
    pairs: list[tuple[str, str]] = []
    en = ""
    kr = ""
    for line in content_04.splitlines():
        stripped = line.strip()
        if stripped.upper().startswith("EN:"):
            en = stripped.split(":", 1)[1].strip()
        elif stripped.upper().startswith("KR:"):
            kr = stripped.split(":", 1)[1].strip()
            if en:
                pairs.append((en, kr))
            en = ""
            kr = ""
    return pairs


def validate_04_en_punctuation(content_04: str) -> tuple[bool, str]:
    en = " ".join(en for en, _kr in _04_paragraph_pairs(content_04))
    sentences = [s for s in split_sentences(en) if s.strip()]
    counts = count_en_punctuation(content_04)
    if len(sentences) >= 40 and counts.get(",", 0) == 0:
        return False, "04 EN punctuation flattened to periods only (comma count 0)"
    return True, "OK"


def count_04_kr_sentence_alignment_mismatches(content_04: str) -> tuple[int, str]:
    mismatches = 0
    sample = ""
    for idx, (en, kr) in enumerate(_04_paragraph_pairs(content_04), start=1):
        if not kr or kr.startswith("[KR"):
            continue
        en_n = len([s for s in split_sentences(en) if s.strip()])
        kr_n = len([s for s in split_sentences(kr) if s.strip()])
        if en_n and kr_n and en_n != kr_n:
            mismatches += 1
            if not sample:
                sample = f"Paragraph {idx}: EN {en_n} vs KR {kr_n}"
    return mismatches, sample


def validate_04_kr_sentence_alignment(content_04: str) -> tuple[bool, str]:
    mismatches, sample = count_04_kr_sentence_alignment_mismatches(content_04)
    if mismatches:
        return False, f"04 KR sentence alignment mismatch ({mismatches}): {sample}"
    return True, "OK"


def validate_format_files(
    files: dict[str, str],
    *,
    segments: list[Segment] | None = None,
    reject_placeholders: bool = True,
) -> tuple[bool, str]:
    required = {
        "00_meta.txt": ["title:", "level:"],
        "01_intro.txt": ["EN:", "KR:"],
        "02_core.txt": ["[Sentence"],
        "03_summary.txt": ["[Part"],
        "04_full_script.txt": ["[Paragraph", "EN:"],
        "05_wordcard.txt": ["[Card"],
    }
    for name, markers in required.items():
        content = files.get(name, "")
        for m in markers:
            if m not in content:
                return False, f"{name} missing {m}"
        if reject_placeholders and "[KR translation pending:" in content:
            return False, f"{name} contains untranslated placeholder KR"

    core_n = _count_blocks(files.get("02_core.txt", ""), "Sentence")
    sum_n = _count_blocks(files.get("03_summary.txt", ""), "Part")
    if core_n != sum_n:
        return False, f"02_core.txt has {core_n} sentences but 03_summary.txt has {sum_n} parts (section mismatch)"
    if core_n < 1:
        return False, "02_core.txt has no sentences (need at least 1 section)"

    verified = _verified_script_text(segments, files.get("04_full_script.txt", ""))
    verified_keys = {
        re.sub(r"\s+", " ", s.strip())
        for s in split_sentences(verified)
        if s.strip()
    }
    for sent in extract_core_sentences(files.get("02_core.txt", "")):
        key = re.sub(r"\s+", " ", sent.strip())
        if key not in verified_keys:
            return False, f"02_core.txt sentence is not an exact Full Script sentence: {sent[:80]}"
        if not is_complete_sentence(sent):
            return False, f"02_core.txt core is not a complete sentence: {sent[:80]}"

    ok, reason = _validate_wordcards(files.get("05_wordcard.txt", ""))
    if not ok:
        return False, reason

    if reject_placeholders:
        ok, reason = validate_04_en_punctuation(files.get("04_full_script.txt", ""))
        if not ok:
            return False, reason
        ok, reason = validate_04_kr_sentence_alignment(files.get("04_full_script.txt", ""))
        if not ok:
            return False, reason

    return True, "OK"
